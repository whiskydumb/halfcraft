"""writes protocol\\halfcraft_protocol.h and minecraft's Proto.java from protocol\\schema\\*.toml (tools/halfcraft/
protocol.py says how the schema reads): make proto. both sides then hold the same layout, and its hash (kLayout,
LAYOUT), which they compare when they link.

    python tools/build/protocol.py           writes what changed
    python tools/build/protocol.py --check   fails if either file isn't what the schema gives (make lint, ci)
"""

import argparse
import re
import sys
from collections.abc import Iterable
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # tools\, where the halfcraft package is
from halfcraft import REPO, ToolError
from halfcraft.protocol import SCALARS, WSTRING, Constant, Enum, Field, Schema, Section, Struct, load, upper_snake

HEADER = REPO / "protocol" / "halfcraft_protocol.h"
PROTO = REPO / "minecraft" / "src" / "main" / "java" / "dev" / "halfcraft" / "link" / "Proto.java"
RULE = 100  # how far a section's heading runs
LAYOUT_DOC = """\
a hash of the layout below but its comments: the host writes it into the header, and Minecraft links only
with a host built from the same schema"""
CPP_BANNER = """\
// HalfCraft's shared memory: the host game (Half-Life 2's client.dll and server.dll) <-> the Minecraft
// Fabric mod. Generated by tools/build/protocol.py from protocol/schema/*.toml, which Minecraft's Proto.java
// comes from too: change the schema and run make proto, never this file."""
JAVA_BANNER = """\
/**
 * HalfCraft's shared memory as protocol/halfcraft_protocol.h lays it out. Generated by tools/build/protocol.py
 * from protocol/schema/*.toml: change the schema and run make proto, never this file.
 */"""


def preceding(doc: str) -> bool:
    """a doc with a line break goes above what it's about; one without trails it."""
    return "\n" in doc


def comments(doc: str, indent: str) -> list[str]:
    return [f"{indent}// {line}".rstrip() for line in doc.splitlines()]


def aligned(rows: Iterable[tuple[str, str]], indent: str) -> list[str]:
    """code with its trailing comment, the comments of rows in a row lined up; a row whose comment has a line
    break gets it above instead, which starts a new run."""
    lines: list[str] = []
    run: list[tuple[str, str]] = []

    def flush() -> None:
        width = max((len(code) for code, doc in run if doc), default=0)
        lines.extend(f"{indent}{code}{' ' * (width - len(code) + 2)}// {doc}" if doc else f"{indent}{code}" for code, doc in run)
        run.clear()

    for code, doc in rows:
        if preceding(doc):
            flush()
            lines.extend(comments(doc, indent))
        run.append((code, "" if preceding(doc) else doc))
    flush()
    return lines


def heading(section: Section, comment: str) -> str:
    text = f"{comment} ---- {section.title} @{hexadecimal(section.at)} "
    return text + "-" * max(4, RULE - len(text))


def hexadecimal(value: int) -> str:
    return f"0x{value:02X}"


# ---- c++


def cpp_string(text: str) -> str:
    return 'L"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cpp_number(value: int | float, kind: str, *, bit: int | None = None, hex_: bool = False) -> str:
    if SCALARS[kind].floating:
        return f"{float(value)!r}f" if kind == "f32" else repr(float(value))
    if bit is not None:
        return f"1ull << {bit}" if SCALARS[kind].size == 8 else f"1u << {bit}"
    return hexadecimal(int(value)) if hex_ or SCALARS[kind].size == 8 else str(value)


def cpp_declarations(rows: list[tuple[str, str, str]], indent: str) -> list[str]:
    """(type, the rest of the declaration, doc) lined up the way clang-format lines up declarations in a row:
    their names in one column, a run broken by a comment line."""
    lines: list[str] = []
    run: list[tuple[str, str, str]] = []

    def flush() -> None:
        width = max((len(kind) for kind, _, _ in run), default=0)
        lines.extend(aligned(((f"{kind:<{width}} {rest}", doc) for kind, rest, doc in run), indent))
        run.clear()

    for kind, rest, doc in rows:
        if preceding(doc):
            flush()
            lines.extend(comments(doc, indent))
        run.append((kind, rest, "" if preceding(doc) else doc))
    flush()
    return lines


def with_expression(doc: str, expression: str) -> str:
    """a constant's doc, with the expression its value came from."""
    if not expression:
        return doc
    return f"{doc}\n{expression}" if preceding(doc) else f"{doc} ({expression})" if doc else expression


def cpp_constants(constants: list[Constant]) -> list[str]:
    rows = []
    for constant in constants:
        doc = with_expression(constant.doc, constant.expression)
        if constant.type == WSTRING:
            rows.append(("inline constexpr wchar_t", f"{constant.name}[] = {cpp_string(str(constant.value))};", doc))
        else:
            value = cpp_number(constant.value, constant.type, bit=constant.bit, hex_=constant.hex)
            rows.append((f"inline constexpr {SCALARS[constant.type].cpp}", f"{constant.name} = {value};", doc))
    return cpp_declarations(rows, "\t")


def cpp_enum(enum: Enum) -> list[str]:
    lines = comments(enum.doc, "\t")
    lines += [f"\tenum {enum.name} : {SCALARS[enum.type].cpp}", "\t{"]
    lines += aligned(((f"{item.name} = {cpp_number(item.value, enum.type, bit=item.bit)},", item.doc) for item in enum.items), "\t\t")
    lines += comments(enum.note, "\t\t")
    lines += ["\t};"]
    return lines


def cpp_type(each: Field) -> str:
    return each.struct.name if each.struct else SCALARS[each.type].cpp


def cpp_struct(struct: Struct) -> list[str]:
    lines = comments(struct.doc, "\t")
    lines += [f"\tstruct {struct.name}", "\t{"]
    rows = []
    for line in sorted({each.line for each in struct.fields}):
        fields = [each for each in struct.fields if each.line == line]
        names = ", ".join(each.name + "".join(f"[{written}]" for written in each.written) for each in fields)
        rows.append((cpp_type(fields[0]), f"{names};", fields[0].doc))
    lines += cpp_declarations(rows, "\t\t")
    lines += comments(struct.note, "\t\t")
    lines += ["\t};", f"\tstatic_assert(sizeof({struct.name}) == {hexadecimal(struct.size)});"]
    return lines


def cpp_regions(schema: Schema) -> list[str]:
    rows: list[tuple[str, str, str]] = []
    lines = ["\t// ---- where each part of the mapping is " + "-" * (RULE - 42)]
    for region in sorted(schema.regions.values(), key=lambda r: r.at):
        if region.reserved:
            lines += cpp_declarations(rows, "\t")
            rows.clear()
            lines += [f"\t// {hexadecimal(region.at)}-{hexadecimal(region.end - 1)}: {region.doc}"]
            continue
        rows.append(("inline constexpr std::uint64_t", f"kOff{region.name} = {hexadecimal(region.at)};", region.doc))
        if region.bytes is not None:
            rows.append(("inline constexpr std::uint64_t", f"k{region.name}Bytes = {hexadecimal(region.bytes)};", region.expression))
    rows.append(("inline constexpr std::uint64_t", f"kMappingBytes = {hexadecimal(schema.mapping_bytes)};", ""))
    return lines + cpp_declarations(rows, "\t")


def cpp_section(section: Section) -> list[str]:
    lines = [f"\t{heading(section, '//')}", *comments(section.doc, "\t")]
    blocks = [cpp_constants(section.constants)] if section.constants else []
    blocks += [cpp_enum(enum) for enum in section.enums]
    blocks += [cpp_struct(struct) for struct in section.structs]
    for block in blocks:
        lines += [*block, ""]
    lines += comments(section.note, "\t")
    return lines


def cpp(schema: Schema) -> str:
    lines = [CPP_BANNER, "#pragma once", "", "#include <cstdint>", "", "namespace halfcraft::proto", "{"]
    lines += [*comments(LAYOUT_DOC, "\t"), f"\tinline constexpr std::uint32_t kLayout = 0x{schema.layout:08X};", ""]
    lines += [*cpp_regions(schema), ""]
    for section in schema.sections:
        lines += cpp_section(section)
    while lines[-1] == "":
        lines.pop()
    lines += ["}"]
    return "\n".join(lines) + "\n"


# ---- java


def java_names(schema: Schema) -> dict[str, str]:
    """c++'s names a doc may mention, and java's for them."""
    names = {name: constant.java for name, constant in schema.constants.items()}
    names |= {name: item.java for name, item in schema.items.items()}
    for region in schema.regions.values():
        names[f"kOff{region.name}"] = f"OFF_{upper_snake(region.name)}"
        names[f"k{region.name}Bytes"] = f"{upper_snake(region.name)}_BYTES"
    return names | {"kLayout": "LAYOUT", "kMappingBytes": "MAPPING_BYTES"}


class Java:
    def __init__(self, schema: Schema) -> None:
        self.schema = schema
        self.names = java_names(schema)
        self.defined: set[str] = set()

    def doc(self, text: str) -> str:
        return re.sub(r"\bk[A-Z]\w*", lambda found: self.names.get(found[0], found[0]), text)

    def constant(self, kind: str, name: str, value: str, doc: str = "") -> list[str]:
        if name in self.defined:
            raise ToolError(f"java gets two constants named {name}: give one of them a java name in the schema")
        self.defined.add(name)
        doc = self.doc(doc)
        code = f"\tpublic static final {kind} {name} = {value};"
        if preceding(doc):
            return [*comments(doc, "\t"), code]
        return [f"{code} // {doc}" if doc else code]

    @staticmethod
    def number(value: int | float, kind: str, *, bit: int | None = None, hex_: bool = False) -> str:
        scalar = SCALARS[kind]
        if scalar.floating:
            return f"{float(value)!r}F" if kind == "f32" else f"{float(value)!r}D"
        if bit is not None:
            return f"1L << {bit}" if scalar.java == "long" else f"1 << {bit}"
        value = int(value)
        big = value > 0x7FFFFFFF
        if scalar.java == "long":
            return f"0x{value:02X}L" if big else hexadecimal(value)
        return f"0x{value:X}" if hex_ or big else str(value)

    def regions(self) -> list[str]:
        lines = ["\t// ---- where each part of the mapping is"]
        for region in sorted(self.schema.regions.values(), key=lambda r: r.at):
            if region.reserved:
                lines += [f"\t// {hexadecimal(region.at)}-{hexadecimal(region.end - 1)}: {region.doc}"]
                continue
            lines += self.constant("long", f"OFF_{upper_snake(region.name)}", self.number(region.at, "u64"), region.doc)
            if region.bytes is not None:
                lines += self.constant("long", f"{upper_snake(region.name)}_BYTES", self.number(region.bytes, "u64"), region.expression)
        return lines + self.constant("long", "MAPPING_BYTES", self.number(self.schema.mapping_bytes, "u64"))

    def constants(self, constants: list[Constant]) -> list[str]:
        lines = []
        for constant in constants:
            doc = with_expression(constant.doc, constant.expression)
            if constant.type == WSTRING:
                text = '"' + str(constant.value).replace("\\", "\\\\").replace('"', '\\"') + '"'
                lines += self.constant("String", constant.java, text, doc)
            else:
                value = self.number(constant.value, constant.type, bit=constant.bit, hex_=constant.hex)
                lines += self.constant(SCALARS[constant.type].java, constant.java, value, doc)
        return lines

    def enum(self, enum: Enum) -> list[str]:
        lines = comments(self.doc(f"{enum.name}\n{enum.doc}" if enum.doc else enum.name), "\t")
        for item in enum.items:
            lines += self.constant(SCALARS[enum.type].java, item.java, self.number(item.value, enum.type, bit=item.bit), item.doc)
        return lines + comments(self.doc(enum.note), "\t")

    def where(self, struct: Struct) -> str:
        """the regions a struct is at, by java's names."""
        regions = [region for region in self.schema.regions.values() if region.type is struct or any(hold.type is struct for hold in region.holds)]
        return f" (in {', '.join(f'OFF_{upper_snake(region.name)}' for region in regions)})" if regions else ""

    def struct(self, struct: Struct) -> list[str]:
        title = f"{struct.name}: offsets in it{self.where(struct)}"
        lines = comments(self.doc(f"{title}\n{struct.doc}" if struct.doc else title), "\t")
        documented: set[int] = set()
        for each in struct.fields:
            if each.padding:
                continue
            doc = "" if each.line in documented else each.doc
            documented.add(each.line)
            lines += self.constant("long", each.java, hexadecimal(each.offset), doc)
            if each.type == "char":
                lines += self.constant("int", f"{each.java}_BYTES", str(each.size))
        lines += self.constant("int", struct.java_size, hexadecimal(struct.size))
        return lines + comments(self.doc(struct.note), "\t")

    def section(self, section: Section) -> list[str]:
        lines = [f"\t{heading(section, '//')}", *comments(self.doc(section.doc), "\t")]
        blocks = [self.constants(section.constants)] if section.constants else []
        blocks += [self.enum(enum) for enum in section.enums]
        blocks += [self.struct(struct) for struct in section.structs]
        for block in blocks:
            lines += [*block, ""]
        return lines + comments(self.doc(section.note), "\t")

    def file(self) -> str:
        lines = ["package dev.halfcraft.link;", "", JAVA_BANNER, "public final class Proto {", "\tprivate Proto() {", "\t}", ""]
        lines += [*self.constant("int", "LAYOUT", f"0x{self.schema.layout:08X}", self.doc(LAYOUT_DOC)), ""]
        lines += [*self.regions(), ""]
        for section in self.schema.sections:
            lines += self.section(section)
        while lines[-1] == "":
            lines.pop()
        lines += ["}"]
        return "\n".join(lines) + "\n"


def outputs(schema: Schema) -> dict[Path, str]:
    return {HEADER: cpp(schema), PROTO: Java(schema).file()}


def main() -> None:
    parser = argparse.ArgumentParser(description="write halfcraft_protocol.h and Proto.java from protocol/schema")
    parser.add_argument("--check", action="store_true", help="fail if they aren't what the schema gives; write nothing")
    options = parser.parse_args()

    schema = load()
    stale = []
    for path, text in outputs(schema).items():
        name = path.relative_to(REPO).as_posix()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(name)
        if not options.check:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {name}")
    if options.check and stale:
        raise ToolError(f"{' and '.join(stale)} aren't what protocol/schema gives: run make proto")
    print(f"protocol: layout 0x{schema.layout:08X}, {len(schema.structs)} structs, {schema.mapping_bytes >> 20} MB mapped")


if __name__ == "__main__":
    main()
